#!/usr/bin/env python3
"""Fail a commit that hand-edits a generated board archive.

Used by .githooks/pre-commit. For each staged board/NNN-*.md, the sha256 of
everything below line 2 must match the hash in the generated header. For a
staged board/MILESTONE-usable-v1.md, only the rows inside the board-table
markers are checked, against the hash comment on the line after the start
marker. This hook reads the index only. It does not use the network or gh.
"""

import hashlib
import re
import subprocess
import sys

CARD_RE = re.compile(r"^board/(\d{3})-.+\.md$")
MILESTONE = "board/MILESTONE-usable-v1.md"
HEADER_RE = re.compile(
    r"^<!-- GENERATED from the Phrase Board \(issue #(\d+), sha256:([0-9a-f]{64})\)\. "
    r"Do not edit this file: edit the issue\. -->$"
)
SHA_LINE_RE = re.compile(br"<!-- board-table-sha256:([0-9a-f]{64}) -->")
TABLE_START = b"<!-- board-table:start -->"
TABLE_END = b"<!-- board-table:end -->"


def card_message(number: str) -> str:
    return (
        f"board/{number} is a generated archive: "
        "edit the issue and run scripts/board/generate_archive.py"
    )


MILESTONE_MESSAGE = (
    "board/MILESTONE-usable-v1.md is a generated archive: "
    "edit the issue and run scripts/board/generate_archive.py"
)


def card_problem(number: str, data: bytes):
    message = card_message(number)
    first = data.find(b"\n")
    if first < 0:
        return message
    second = data.find(b"\n", first + 1)
    if second < 0:
        return message
    header = data[first + 1:second].decode("utf-8", errors="replace")
    match = HEADER_RE.fullmatch(header)
    if not match:
        return message
    digest = hashlib.sha256(data[second + 1:]).hexdigest()
    if digest != match.group(2):
        return message
    return None


def milestone_problem(data: bytes):
    start = data.find(TABLE_START)
    end = data.find(TABLE_END)
    if start < 0 or end < 0 or end < start:
        return MILESTONE_MESSAGE
    newline = data.find(b"\n", start + len(TABLE_START))
    if newline < 0 or newline >= end:
        return MILESTONE_MESSAGE
    line_end = data.find(b"\n", newline + 1)
    if line_end < 0 or line_end > end:
        return MILESTONE_MESSAGE
    match = SHA_LINE_RE.fullmatch(data[newline + 1:line_end])
    if not match:
        return MILESTONE_MESSAGE
    rows = data[line_end + 1:end]
    if hashlib.sha256(rows).hexdigest().encode("ascii") != match.group(1):
        return MILESTONE_MESSAGE
    return None


def staged_names():
    proc = subprocess.run(["git", "diff", "--cached", "--name-only"], capture_output=True)
    if proc.returncode != 0:
        raise RuntimeError("board archive check could not read the index")
    names = []
    for line in proc.stdout.decode("utf-8", errors="replace").splitlines():
        name = line.strip().replace("\\", "/")
        if name:
            names.append(name)
    return names


def staged_blob(name: str):
    proc = subprocess.run(["git", "cat-file", "blob", f":{name}"], capture_output=True)
    if proc.returncode != 0:
        return None
    return proc.stdout


def problems():
    found = []
    for name in staged_names():
        card = CARD_RE.match(name)
        if card:
            data = staged_blob(name)
            if data is None:
                found.append(card_message(card.group(1)))
                continue
            problem = card_problem(card.group(1), data)
            if problem:
                found.append(problem)
            continue
        if name == MILESTONE:
            data = staged_blob(name)
            if data is None:
                found.append(MILESTONE_MESSAGE)
                continue
            problem = milestone_problem(data)
            if problem:
                found.append(problem)
    return found


def cut_over():
    """The hook enforces only after the cutover: board/CUTOVER in the working tree or the index."""
    import os

    if os.path.exists(os.path.join("board", "CUTOVER")):
        return True
    return subprocess.run(["git", "cat-file", "-e", ":board/CUTOVER"], capture_output=True).returncode == 0


def main():
    if not cut_over():
        return 0
    try:
        found = problems()
    except RuntimeError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    if found:
        for line in found:
            print(line, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Regenerate board/NNN-*.md and the rank table from the Phrase Board.

The GitHub project is canonical. This writes a read-only archive. The default
is a dry run that lists ``write NNN`` or ``unchanged NNN``. ``--apply`` writes.
``--check`` is read-only and exits 1 when a generated file would change.
A card file with no marked issue is reported and never deleted. Owner and
repo are hard-wired; anything else is refused. The script never deletes.
"""

import argparse
import hashlib
import json
import os
import re
import subprocess
from pathlib import Path
from typing import Sequence

OWNER = "Programming-Made-EZ"
REPO = "avowry"
PROJECT_NUMBER = 1
BOARD_DIR = Path(__file__).resolve().parents[2] / "board"
MILESTONE_NAME = "MILESTONE-usable-v1.md"
CARD_FILE_RE = re.compile(r"^(\d{3})-.+\.md$")
MARKER_RE = re.compile(r"<!-- phrase-card:(\d{3}) -->")
MARKER_LINE_RE = re.compile(r"<!-- phrase-card:\d{3} -->")
TITLE_PREFIX_RE = re.compile(r"^\(\d{3}\)\s+")
TABLE_RE = re.compile(r"(?m)^\| Rank \|.*(?:\n\|.*)*(?:\n|$)")
TABLE_START = "<!-- board-table:start -->"
TABLE_END = "<!-- board-table:end -->"
DEFAULT_MOB_DEFAULTS = r"C:\Users\ringe\mob-crosscli"


def repo_root() -> Path:
    """The checkout that contains this script. Placeholders expand to this path."""
    return Path(__file__).resolve().parents[2]


def mob_defaults() -> str:
    value = os.environ.get("MOB_DEFAULTS")
    if value:
        return value
    return DEFAULT_MOB_DEFAULTS


def gh_runner(args: Sequence[str], *, check: bool = True, input_text: str | None = None):
    proc = subprocess.run(
        ["gh", *[str(part) for part in args]],
        input=input_text,
        capture_output=True,
        text=True,
    )
    if check and proc.returncode != 0:
        detail = proc.stderr.strip() or proc.stdout.strip()
        raise RuntimeError(detail or f"gh command failed: {' '.join(str(part) for part in args)}")
    return proc.stdout.strip()


def ensure_target(owner: str, repo: str):
    if owner != OWNER or repo != REPO:
        raise ValueError(f"Owner and repo must be {OWNER}/{REPO}; refusing {owner}/{repo}.")


def call_gh(gh, args):
    command = [str(part) for part in args]
    if any(part.lower() == "delete" for part in command):
        raise RuntimeError("Refusing a gh command that includes delete.")
    return gh(command, check=True)


def normalise_newlines(text: str) -> str:
    return (text or "").replace("\r\n", "\n").replace("\r", "\n")


def card_title(title: str) -> str:
    return TITLE_PREFIX_RE.sub("", title or "", count=1).strip()


def slugify(title: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", (title or "").lower()).strip("-")
    return slug or "card"


def expand_paths(text: str) -> str:
    return text.replace("<phrase-lang>", str(repo_root())).replace("<mob-defaults>", mob_defaults())


def strip_marker(text: str) -> str:
    """Drop the phrase-card marker line. The rest of the body is unchanged."""
    first, sep, rest = text.partition("\n")
    if MARKER_LINE_RE.fullmatch(first.strip()):
        return rest if sep else ""
    lines = text.split("\n")
    dropped = False
    kept = []
    for line in lines:
        if not dropped and MARKER_LINE_RE.fullmatch(line.strip()):
            dropped = True
            continue
        kept.append(line)
    return "\n".join(kept)


def archive_text(issue: dict, number: str) -> str:
    """One generated card: H1, hash header, a blank line, then the issue body."""
    title = card_title(str(issue.get("title") or ""))
    body = normalise_newlines(str(issue.get("body") or ""))
    rest = expand_paths(strip_marker(body))
    below = "\n" + rest  # the blank line under the header, then the body
    digest = hashlib.sha256(below.encode("utf-8")).hexdigest()
    header = (
        f"<!-- GENERATED from the Phrase Board (issue #{int(issue['number'])}, sha256:{digest}). "
        "Do not edit this file: edit the issue. -->"
    )
    return f"# {title}\n{header}\n{below}"


def fetch_issues(gh, owner: str, repo: str):
    payload = call_gh(gh, [
        "issue", "list", "--repo", f"{owner}/{repo}", "--state", "all", "--limit", "1000",
        "--json", "number,title,body,state",
    ])
    if payload is None or not str(payload).strip():
        return []
    data = json.loads(payload)
    if not isinstance(data, list):
        raise RuntimeError("Issue list did not return a JSON array.")
    return data


def fetch_items(gh, owner: str):
    payload = call_gh(gh, [
        "project", "item-list", str(PROJECT_NUMBER), "--owner", owner,
        "--format", "json", "--limit", "1000",
    ])
    if payload is None or not str(payload).strip():
        return []
    data = json.loads(payload)
    if isinstance(data, dict):
        items = data.get("items", [])
    elif isinstance(data, list):
        items = data
    else:
        items = []
    if not isinstance(items, list):
        raise RuntimeError("Project item list did not return items.")
    return items


def index_issues(issues) -> dict:
    found = {}
    for issue in issues:
        if not isinstance(issue, dict):
            continue
        numbers = set(MARKER_RE.findall(issue.get("body") or ""))
        if len(numbers) > 1:
            raise RuntimeError(f"Issue {issue.get('number')} carries more than one phrase-card marker.")
        for number in numbers:
            if number in found:
                raise RuntimeError(f"More than one issue carries phrase-card:{number}")
            found[number] = issue
    return found


def group_card_files(board: Path) -> dict:
    grouped = {}
    for path in sorted(board.iterdir(), key=lambda item: item.name):
        match = CARD_FILE_RE.match(path.name)
        if match and path.is_file():
            grouped.setdefault(match.group(1), []).append(path)
    return grouped


def escape_cell(value) -> str:
    if value is None:
        return ""
    text = str(value).replace("\r\n", " ").replace("\n", " ").replace("\r", " ").replace("|", "\\|")
    return text.strip()


def format_rank(value) -> str:
    number = float(value)
    if number.is_integer():
        return str(int(number))
    return str(number)


def format_card_number(value) -> str:
    return f"{int(float(value)):03d}"


def card_column(item: dict) -> str:
    title = card_title(str(item.get("title") or ""))
    number = item.get("card number")
    if number is None or str(number).strip() == "":
        return escape_cell(title)
    try:
        label = format_card_number(number)
    except (TypeError, ValueError):
        label = str(number).strip()
    return escape_cell(f"{label} {title}".strip())


def card_sort_key(item: dict):
    number = item.get("card number")
    try:
        return int(float(number))
    except (TypeError, ValueError):
        return 10**9


def ranked_items(items) -> list:
    ranked = []
    for item in items:
        if not isinstance(item, dict) or "rank" not in item or item.get("rank") is None:
            continue
        try:
            float(item["rank"])
        except (TypeError, ValueError):
            continue
        ranked.append(item)
    return sorted(ranked, key=lambda item: (float(item["rank"]), card_sort_key(item)))


def table_rows(items) -> str:
    lines = [
        "| Rank | Card | Status | Depends on |",
        "|---|---|---|---|",
    ]
    for item in ranked_items(items):
        rank = format_rank(item["rank"])
        status = escape_cell(item.get("status"))
        depends = escape_cell(item.get("depends on"))
        lines.append(f"| {rank} | {card_column(item)} | {status} | {depends} |")
    return "\n".join(lines) + "\n"


def ensure_markers(text: str) -> str:
    """Put the table markers around the current rank table. Prose outside it stays."""
    if TABLE_START in text and TABLE_END in text:
        return text
    block = f"{TABLE_START}\n{TABLE_END}\n"
    match = TABLE_RE.search(text)
    if not match:
        prefix = text
        if prefix and not prefix.endswith("\n"):
            prefix += "\n"
        return prefix + block
    # The match includes the table's own trailing newline, so the following prose stays put.
    return text[:match.start()] + block + text[match.end():]


def render_milestone(original: str, items) -> str:
    rows = table_rows(items)
    digest = hashlib.sha256(rows.encode("utf-8")).hexdigest()
    text = ensure_markers(original)
    start_at = text.find(TABLE_START)
    end_at = text.find(TABLE_END)
    if start_at < 0 or end_at < 0 or end_at < start_at:
        raise RuntimeError("board table markers missing from MILESTONE-usable-v1.md")
    after = start_at + len(TABLE_START)
    if text.startswith("\r\n", after):
        after += 2
    elif text.startswith("\n", after):
        after += 1
    else:
        raise RuntimeError("board table start marker is not on its own line")
    interior = f"<!-- board-table-sha256:{digest} -->\n{rows}"
    return text[:after] + interior + text[end_at:]


def same_bytes(path: Path, desired: str) -> bool:
    return path.is_file() and path.read_bytes() == desired.encode("utf-8")


def generate(gh, board: Path, owner: str = OWNER, repo: str = REPO, *, write: bool = False):
    ensure_target(owner, repo)
    board = Path(board)
    if not board.is_dir():
        raise RuntimeError(f"Board directory does not exist: {board}")
    marked = index_issues(fetch_issues(gh, owner, repo))
    items = fetch_items(gh, owner)
    grouped = group_card_files(board)
    lines = []
    reports = []
    changed = False
    for number in sorted(marked):
        issue = marked[number]
        desired = archive_text(issue, number)
        paths = grouped.get(number, [])
        if paths:
            target = paths[0]
            extras = paths[1:]
        else:
            target = board / f"{number}-{slugify(card_title(str(issue.get('title') or '')))}.md"
            extras = []
        if same_bytes(target, desired):
            lines.append(f"unchanged {number}")
        else:
            lines.append(f"write {number}")
            changed = True
            if write:
                target.write_bytes(desired.encode("utf-8"))
        for extra in extras:
            reports.append(f"extra {number} {extra.name}")
    for number in sorted(set(grouped) - set(marked)):
        for path in grouped[number]:
            reports.append(f"no-issue {number} {path.name}")
    milestone = board / MILESTONE_NAME
    original = milestone.read_bytes().decode("utf-8") if milestone.is_file() else ""
    desired_milestone = render_milestone(original, items)
    if same_bytes(milestone, desired_milestone):
        lines.append("unchanged table")
    else:
        lines.append("write table")
        changed = True
        if write:
            milestone.write_bytes(desired_milestone.encode("utf-8"))
    lines.extend(reports)
    return lines, changed


def main(argv: Sequence[str] | None = None, gh_runner=gh_runner, board_dir=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true", help="write the archive")
    parser.add_argument("--dry-run", action="store_true", help="list write/unchanged and change nothing")
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated file would change; write nothing")
    parser.add_argument("--owner", default=OWNER, help="GitHub owner; must be Programming-Made-EZ")
    parser.add_argument("--repo", default=REPO, help="GitHub repo; must be avowry")
    args = parser.parse_args(argv)
    if args.owner != OWNER or args.repo != REPO:
        raise ValueError(f"Owner and repo must be {OWNER}/{REPO}; refusing {args.owner}/{args.repo}.")
    board = Path(board_dir) if board_dir is not None else BOARD_DIR
    write = bool(args.apply and not args.dry_run and not args.check)
    try:
        lines, changed = generate(gh_runner, board, args.owner, args.repo, write=write)
    except ValueError:
        raise
    except Exception as exc:
        print(f"ERROR: {exc}")
        return 1
    for line in lines:
        print(line)
    if args.check and changed:
        return 1
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except ValueError as exc:
        print(f"ERROR: {exc}")
        raise SystemExit(2)

import hashlib
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLACEHOLDER = "[COPYRIGHT HOLDER: to be confirmed by the product owner at the pre-publication checks (card 186)]"
APACHE_2_0_SHA256 = "cfc7749b96f63bd31c3c42b5c471bf756814053e847c10f3eb003417bc523d30"
GENERATED_CODE_STATEMENT = "Code generated by the Avowry compiler belongs to you, with no license obligations from the toolchain."
HOLDER = "Programming Made EZ"
BRACKET_TOKEN = re.compile(r"\[[A-Z][A-Z0-9 :_-]{2,}[^\]\n]*\](?!\()")
PLACEHOLDER_PATTERNS = (
    ("card-186-text", re.compile(re.escape(PLACEHOLDER))),
    ("[YEAR]", re.compile(r"\[YEAR\]", re.IGNORECASE)),
    ("to-be-confirmed", re.compile(r"to be confirmed", re.IGNORECASE)),
    ("bracket-token", BRACKET_TOKEN),
)


def read(name: str) -> str:
    return (ROOT / name).read_text(encoding="utf-8")


def placeholder_hits(text: str) -> list:
    hits = []
    for number, line in enumerate(text.splitlines(), start=1):
        for label, pattern in PLACEHOLDER_PATTERNS:
            if pattern.search(line):
                hits.append(f"line {number}: {label}")
    return hits


class LicenseFilesTests(unittest.TestCase):
    def test_reader_facing_legal_files_use_the_avowry_name(self):
        # Given Dana is reading the project's public legal and licensing pages
        documents = {
            name: read(name)
            for name in ("README.md", "TRADEMARKS.md", "NOTICE", "docs/LICENSING.md")
        }

        # When she looks for the product and project names
        # Then every page identifies Avowry, without presenting Phrase as the product
        for name, text in documents.items():
            self.assertIn("Avowry", text, name)
            self.assertNotRegex(text, r"(?i)\bPhrase (?:compiler|project|toolchain)\b", name)

        for name in ("TRADEMARKS.md", "NOTICE", "docs/LICENSING.md"):
            self.assertNotRegex(documents[name], r"\bPhrase\b", name)
        for name in ("VISION.md", "docs/release/v0.1-bar.md"):
            self.assertIn("Avowry", read(name), name)
        self.assertIn("uses the `avowry` command and still uses the `.avowry` file extension", documents["README.md"])
        self.assertTrue(documents["README.md"].startswith("# Avowry\n"))
        self.assertTrue(documents["NOTICE"].startswith("Avowry\n"))

        # And the README explains the language's unit in one sentence
        self.assertIn(
            "Avowry is the language; each avow is one line of intent in it.",
            documents["README.md"],
        )

    def test_license_is_the_standard_apache_2_0_text_byte_for_byte(self):
        # Given the LICENSE file
        data = (ROOT / "LICENSE").read_bytes()

        # When it is hashed (line endings normalised, as git may convert them)
        digest = hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()

        # Then it is the standard Apache License 2.0 text published by the Apache Software Foundation
        self.assertEqual(APACHE_2_0_SHA256, digest)

    def test_notice_and_trademarks_name_the_holder_and_the_year(self):
        # Given the files that name the copyright holder and the year
        notice_line = read("NOTICE").splitlines()[1]
        parts = notice_line.split(" ", 2)
        trademark_line = read("TRADEMARKS.md").splitlines()[4]

        # When they are read, Then NOTICE names the holder, NOTICE names the year, TRADEMARKS.md names the holder
        with self.subTest(id="N1"):
            self.assertEqual(HOLDER, parts[2] if len(parts) == 3 else "", "NOTICE line 2 holder: " + notice_line)
        with self.subTest(id="N2"):
            self.assertEqual(["Copyright", "2026"], parts[:2], "NOTICE line 2 year: " + notice_line)
        with self.subTest(id="T1"):
            self.assertEqual("Trademark holder: " + HOLDER, trademark_line, "TRADEMARKS.md line 5")

        # And the holder line is the only one, so a second copyright line cannot contradict it
        with self.subTest(id="N3"):
            self.assertEqual(1, read("NOTICE").count("Copyright "))

    def test_notice_and_trademarks_hold_no_placeholder(self):
        # Given the two files that name the holder
        # When the placeholder scanner reads them, Then it finds nothing
        with self.subTest(id="G1"):
            self.assertEqual([], placeholder_hits(read("NOTICE")), "NOTICE")
        with self.subTest(id="G2"):
            self.assertEqual([], placeholder_hits(read("TRADEMARKS.md")), "TRADEMARKS.md")

    def test_the_placeholder_scanner_reports_planted_placeholders(self):
        # Given a text with a planted placeholder, When it is scanned, Then the exact hits are reported
        rows = (
            ("P1", "Copyright [YEAR] Acme", ["line 1: [YEAR]", "line 1: bracket-token"]),
            (
                "P2",
                "Copyright [YEAR] " + PLACEHOLDER,
                ["line 1: card-186-text", "line 1: [YEAR]", "line 1: to-be-confirmed", "line 1: bracket-token"],
            ),
            ("P3", "Trademark holder: [HOLDER NAME]", ["line 1: bracket-token"]),
            ("P4", "Name\nholder to be confirmed by the product owner", ["line 2: to-be-confirmed"]),
        )
        for row_id, text, expected in rows:
            with self.subTest(id=row_id):
                self.assertEqual(expected, placeholder_hits(text), text)

    def test_the_placeholder_scanner_ignores_links_and_the_filled_holder(self):
        # Given a markdown link and the filled holder line, When they are scanned, Then there are no hits
        with self.subTest(id="X1"):
            self.assertEqual([], placeholder_hits("See [LICENSE](LICENSE)."))
        with self.subTest(id="X2"):
            self.assertEqual([], placeholder_hits("Copyright 2026 " + HOLDER))

    def test_the_licensing_page_names_the_holder_and_the_year_assumption(self):
        # Given the licensing page a sponsor reads
        text = read("docs/LICENSING.md")

        # When it is read, Then it names the holder, says the year is an assumption, and no longer calls the holder a placeholder
        with self.subTest(id="L1"):
            for needle in (HOLDER, "2026", "assumption"):
                self.assertIn(needle, text, needle)
            self.assertNotIn("marked placeholder", text)

    def test_the_readme_and_the_licensing_page_say_generated_code_belongs_to_the_user(self):
        # Given the two places a reader looks for the terms of generated code
        for name in ("README.md", "docs/LICENSING.md"):
            # When they are read, Then each states the user owns what the compiler generates, with no obligations
            self.assertIn(GENERATED_CODE_STATEMENT, read(name), name)

    def test_the_trademark_policy_covers_redistribution_references_forks_and_the_rationale(self):
        text = read("TRADEMARKS.md")
        for needle in ("unmodified toolchain", "compatible with Avowry", "must be renamed", "official, accountable"):
            self.assertIn(needle, text, needle)

    def test_the_licensing_page_states_the_apache_licence_and_links_the_trademark_policy(self):
        text = read("docs/LICENSING.md")
        self.assertIn("Apache License, Version 2.0", text)
        self.assertIn("TRADEMARKS.md", text)
        self.assertIn("NOTICE", text)


if __name__ == "__main__":
    unittest.main()

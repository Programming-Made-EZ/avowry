def relative_targets(text):
    out = []
    for raw in LINK.findall(text):
        if SCHEME.match(raw) or raw.startswith("#") or raw.startswith("//"):
            continue
        target = raw.split("#", 1)[0].split("?", 1)[0]
        if target:
            out.append(target)
    return out


def in_order(block, source):
    lines, index = source.splitlines(), 0
    for line in block.splitlines():
        if not line.strip():
            continue
        while index < len(lines) and lines[index] != line:
            index += 1
        if index >= len(lines):
            return False
        index += 1
    return True


def newer_sdk_failures(text):
    if any(
        "newer SDK" in s and "untested" in s and "does not replace" in s and ".NET 8 SDK" in s
        for s in sentences(text)
    ):
        return []
    return ["newer-sdk: no sentence holds newer SDK, untested, does not replace and .NET 8 SDK"]


def story_failures(readme, guide, prereq, tasks, exists, retired):
    failures = []

    def fail(cid, message):
        failures.append(f"{cid}: {message}")

    def need(cid, ok, message=None):
        if not ok:
            fail(cid, message or cid)

    if readme is None:
        fail("readme", "README.md is missing")
    else:
        text = normalize(readme)
        need("h1", text.startswith("# Avowry\n"), "H1 is not # Avowry")
        for cid, needle in KEEPS:
            need(cid, needle in text, "missing")
        need("rename-line", text.count(RENAME) == 1, "rename line must appear once")
        need("dana-agent", any("Dana" in p and "agent" in p for p in paragraphs(text)))
        need("known-limitations", "known limitations" in text and "card 187" in text)
        for cid, pattern in DROPS:
            need(cid, re.search(pattern, text) is None, "still present")
        need("line-count", len(text.splitlines()) <= 50, "README is more than 50 lines")
        missing = [t for t in relative_targets(text) if not exists(t)]
        need("relative-links", not missing, "unresolved: " + ", ".join(missing))
        need("status-script-retired", retired, "status script or its test is still present")
    if prereq is None:
        fail("prereq-page", "docs/PREREQUISITES.md is missing")
    else:
        failures.extend(newer_sdk_failures(prereq))
        failures.extend(collect_failures(prereq, parse_all_workflows()))
    if guide is None:
        fail("page", "docs/GETTING_STARTED.md is missing")
        for cid in GUIDE_IDS:
            fail(cid, "blocked: page missing")
        return failures
    g = normalize(guide)
    blocks = [(fence_lang(m.group(1)), m.group(2)) for m in FENCE.finditer(g)]
    need("clone", CLONE in g and re.search(r"(?i)\bclone\b", g))
    need("dotnet-pack", "dotnet pack src/Avowry.Cli/Avowry.Cli.csproj" in g)
    need("tool-install", "dotnet tool install Avowry --tool-path" in g and "--add-source" in g)
    need("no-angle-brackets", not any(re.search(r"<[^>\s]+>", body) for _, body in blocks))
    need("avowry-build", BUILD.search(g))
    need("no-dev-cli", not any(DEV_CLI in body for _, body in blocks))
    listing = next((body for lang, body in blocks if lang == "avowry"), "")
    need("avowry-listing", listing and in_order(listing, tasks))
    need("listing-create", "POST /tasks" in listing)
    need("listing-read", "GET /tasks/{id}" in listing)
    need("listing-fails", "fails with" in listing)
    n = len(re.findall(r'(?m)^\s*spec\s+"', tasks))
    need("dotnet-test-specs", re.search(r"dotnet test \S*Tasks\.Specs", g))
    need("passed-n", f"Passed: {n}" in g)
    need(
        "dotnet-run-api",
        re.search(r"dotnet run --project \S*Tasks\.Api\b[^\n]*--urls http://localhost:5099", g),
    )
    rest = g
    for lang, body in blocks:
        if lang == "avowry":
            rest = rest.replace(body, "")
    need("create-call", re.search(r"(?i)\bpost\b", rest) and "/tasks" in rest)
    need("read-call", re.search(r"/tasks/", rest))
    declared = [
        part.strip()
        for found in re.findall(r"fails with\s+([A-Za-z0-9_, ]+)", tasks)
        for part in found.split(",")
        if part.strip()
    ]
    need("failure-422", "422" in rest and any(name in rest for name in declared))
    need("source-avowry", any(".avowry" in s and "source" in s.lower() for s in sentences(g)))
    need("generated-output", any("generated" in s.lower() and "output" in s.lower() for s in sentences(g)))
    need(
        "rebuild-leftovers",
        any("overwrites" in s and "relative paths" in s and "leftover" in s for s in sentences(g)),
    )
    need("guide-prerequisites-link", "docs/PREREQUISITES.md" in g)
    need("guide-net8", ".NET 8 SDK" in g)
    cmd = command_failures(g)
    if cmd:
        failures.extend(cmd)
    pwsh = [body for lang, body in blocks if lang in PWSH]
    need("pwsh-windows-path", any(WIN_PATH.search(body) for body in pwsh))
    need("pwsh-no-tmp", not any("/tmp/" in body for body in pwsh))
    need("pwsh-no-bare-curl", not any(BARE_CURL.search(body) for body in pwsh))
    need("pwsh-http-client", any("Invoke-RestMethod" in body or "curl.exe" in body for body in pwsh))
    need("guide-no-phrase", not re.search(r"\bPhrase\b", g))
    need("guide-no-wasm", "Wasm" not in g)
    need("guide-no-resolver", not re.search(r"(?i)resolver", g))
    return failures


def check(readme, guide, prereq, tasks):
    return story_failures(readme, guide, prereq, tasks, exists=lambda _p: True, retired=True)


class GettingStartedSelfTests(unittest.TestCase):
    def test_compliant_fixtures_give_no_failures(self):
        self.assertEqual([], check(COMPLIANT_README, COMPLIANT_GUIDE, NEW_PREREQ, COMPLIANT_TASKS))

    def test_missing_guide_reports_page_missing_and_blocked_ids_without_exception(self):
        failures = check(COMPLIANT_README, None, NEW_PREREQ, COMPLIANT_TASKS)
        ids = [item.split(":", 1)[0] for item in failures]
        self.assertIn("page", ids)
        self.assertTrue(any("docs/GETTING_STARTED.md is missing" in item for item in failures))
        for cid in GUIDE_IDS:
            self.assertIn(cid, ids, failures)
            self.assertTrue(
                any(item.startswith(cid + ":") and "blocked: page missing" in item for item in failures),
                cid,
            )

    def test_restyled_readme_table_fails(self):
        failures = check(COMPLIANT_README + "\n| kept |\n", COMPLIANT_GUIDE, NEW_PREREQ, COMPLIANT_TASKS)
        self.assertTrue(any(item.startswith("table-row:") for item in failures), failures)

    def test_curl_bash_without_pwsh_fails(self):
        extra = "\nRun from: anywhere\nNeeds: the API\n\n```bash\ncurl http://localhost:5099/tasks/task-1\n```\n"
        failures = check(COMPLIANT_README, COMPLIANT_GUIDE + extra, NEW_PREREQ, COMPLIANT_TASKS)
        self.assertNotEqual([], failures)

    def test_pwsh_block_with_bare_curl_fails(self):
        extra = "\n```pwsh\ncurl http://localhost:5099/tasks\n```\n"
        failures = check(COMPLIANT_README, COMPLIANT_GUIDE + extra, NEW_PREREQ, COMPLIANT_TASKS)
        self.assertTrue(any(item.startswith("pwsh-no-bare-curl:") for item in failures), failures)

    def test_old_prerequisites_newer_sdk_fails_and_new_wording_passes(self):
        self.assertTrue(any(i.startswith("newer-sdk:") for i in newer_sdk_failures(OLD_SDK_LINES)))
        self.assertEqual([], newer_sdk_failures(NEW_SDK))


class GettingStartedTests(unittest.TestCase):
    def test_readme_and_guide_match_the_story(self):
        readme = README_PATH.read_text(encoding="utf-8") if README_PATH.is_file() else None
        guide = GUIDE_PATH.read_text(encoding="utf-8") if GUIDE_PATH.is_file() else None
        failures = story_failures(
            readme, guide, read_page(), TASKS_PATH.read_text(encoding="utf-8"),
            exists=lambda t: (REPO / t).exists(),
            retired=not SCRIPT.is_file() and not SCRIPT_TEST.is_file(),
        )
        self.assertEqual([], failures, HEADER + "\n".join(failures))



    def test_rank_table_is_rebuilt_only_between_markers(self):
        # Given a milestone whose prose surrounds an old rank table, and items with and without a Rank
        prefix = "Intro stays.\n\n## Cards\n\n"
        suffix = "\nTail stays.\n"
        old = (
            prefix
            + "| Rank | Card | Why here | Origin |\n"
            + "|---|---|---|---|\n"
            + "| 1 | 002 Old row | because | someone |\n"
            + suffix
        )
        items = [
            item(1, 1.0, "Build the resolver", "Ready", 2.0, "none", 41),
            {"title": "(003) No rank", "status": "Ready", "card number": 3, "depends on": "none",
             "content": {"number": 43, "url": f"https://github.com/{SLUG}/issues/43"}},
            item(2, 2.0, "Harden", "Done", 1.0, "001", 42),
        ]
        fake = FakeGH(issues=[], items=items)
        with tempfile.TemporaryDirectory() as tmp:
            board = Path(tmp)
            milestone = board / "MILESTONE-usable-v1.md"
            milestone.write_bytes(old.encode("utf-8"))
            # When the archive is applied
            code, out = run(["--apply"], fake, board)
            updated = milestone.read_text(encoding="utf-8")
        # Then only the table between the new markers changes
        self.assertEqual(code, 0)
        self.assertIn("write table", out)
        self.assertTrue(updated.startswith(prefix))
        self.assertTrue(updated.endswith(suffix))
        self.assertNotIn("Old row", updated)
        self.assertNotIn("Why here", updated)
        self.assertNotIn("No rank", updated)
        self.assertIn("<!-- board-table:start -->\n", updated)
        self.assertIn("<!-- board-table:end -->", updated)
        self.assertLess(updated.index("| 1 | 002 Harden | Done | 001 |"), updated.index("| 2 | 001 Build the resolver | Ready | none |"))
        rows = table_row_bytes(updated.encode("utf-8"))
        digest = hashlib.sha256(rows).hexdigest()
        self.assertIn(f"<!-- board-table-sha256:{digest} -->", updated)
        self.assertTrue(rows.startswith(b"| Rank | Card | Status | Depends on |\n"))

    def test_existing_table_markers_keep_the_prose_around_them(self):
        # Given markers already around a hand-written table
        prefix = "NOTE: keep me.\n\n"
        suffix = "\nTAIL keep me.\n"
        old = (
            prefix
            + "<!-- board-table:start -->\n"
            + "<!-- board-table-sha256:" + ("a" * 64) + " -->\n"
            + "| Rank | Card | Status | Depends on |\n"
            + "|---|---|---|---|\n"
            + "| 9 | 001 hand | Ready | x |\n"
            + "<!-- board-table:end -->"
            + suffix
        )
        fake = FakeGH(issues=[], items=[item(1, 4, "Four", "Ready", 3, "none", 9)])
        with tempfile.TemporaryDirectory() as tmp:
            board = Path(tmp)
            milestone = board / "MILESTONE-usable-v1.md"
            milestone.write_bytes(old.encode("utf-8"))
            # When the archive is applied
            run(["--apply"], fake, board)
            updated = milestone.read_bytes().decode("utf-8")
        # Then the prose outside the markers is byte-for-byte the same
        self.assertTrue(updated.startswith(prefix))
        self.assertTrue(updated.endswith(suffix))
        self.assertNotIn("| 9 | 001 hand |", updated)
        self.assertIn("| 3 | 004 Four | Ready | none |", updated)

    def test_check_fails_after_a_hand_edit_and_passes_after_regeneration(self):
        # Given a generated archive
        fake = FakeGH(
            issues=[issue(15, "007", "CLI build command", "<!-- phrase-card:007 -->\n\nBody.\n")],
            items=[item(1, 7, "CLI build command", "Ready", 1, "none", 15)],
        )
        with tempfile.TemporaryDirectory() as tmp:
            board = Path(tmp)
            (board / "MILESTONE-usable-v1.md").write_bytes(b"Intro stays.\n\nTail stays.\n")
            self.assertEqual(run(["--apply"], fake, board)[0], 0)
            self.assertEqual(run(["--check"], fake, board)[0], 0)
            card = board / "007-cli-build-command.md"
            card.write_bytes(card.read_bytes().replace(b"Body.", b"Body. EDIT"))
            # When --check runs after the hand edit, including with --apply beside it
            code, out = run(["--check"], fake, board)
            still = card.read_bytes()
            code_both, _out_both = run(["--check", "--apply"], fake, board)
            after_check = card.read_bytes()
            # And when the archive is regenerated
            self.assertEqual(run(["--apply"], fake, board)[0], 0)
            code_clean, _clean = run(["--check"], fake, board)
            milestone = (board / "MILESTONE-usable-v1.md").read_bytes()
            edited = milestone.replace(b"| Ready |", b"| Hand |")
            (board / "MILESTONE-usable-v1.md").write_bytes(edited)
            code_table, _table = run(["--check"], fake, board)
            table_still = (board / "MILESTONE-usable-v1.md").read_bytes()
        # Then the check fails while the hand edit is present, and passes once the issue wins again
        self.assertEqual(code, 1)
        self.assertIn("write 007", out)
        self.assertIn(b"EDIT", still)
        self.assertEqual(code_both, 1)
        self.assertEqual(after_check, still)
        self.assertEqual(code_clean, 0)
        self.assertEqual(code_table, 1)
        self.assertIn(b"| Hand |", table_still)

    def test_a_card_file_with_no_issue_is_reported_and_not_deleted(self):
        # Given a board file whose number has no marked issue, and a title that says delete
        fake = FakeGH(
            issues=[issue(15, "007", "do not delete cards", "<!-- phrase-card:007 -->\n\nPresent.\n")],
            items=[],
        )
        with tempfile.TemporaryDirectory() as tmp:
            board = Path(tmp)
            orphan = board / "009-legacy.md"
            orphan.write_bytes(b"keep me\n")
            # When the archive is applied
            code, out = run(["--apply"], fake, board)
            left = orphan.read_bytes()
            present = (board / "007-do-not-delete-cards.md").is_file()
        # Then the orphan remains and gh is never asked to delete
        self.assertEqual(code, 0)
        self.assertEqual(left, b"keep me\n")
        self.assertIn("no-issue 009 009-legacy.md", out)
        self.assertTrue(present)
        assert_no_delete(self, fake)


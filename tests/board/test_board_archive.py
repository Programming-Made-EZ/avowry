class HookTests(unittest.TestCase):
    def test_hook_accepts_a_generated_card_and_rejects_a_hand_edit_and_a_missing_header(self):
        # Given a generated card staged in a fresh repo
        fake = FakeGH(
            issues=[issue(15, "007", "CLI build command", "<!-- phrase-card:007 -->\n\nBody.\n")],
            items=[],
        )
        message = "board/007 is a generated archive: edit the issue and run scripts/board/generate_archive.py"
        missing = "board/004 is a generated archive: edit the issue and run scripts/board/generate_archive.py"
        with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
            repo = Path(tmp)
            board = repo / "board"
            board.mkdir()
            init_repo(repo)
            (board / "CUTOVER").write_text("cut over\n", encoding="utf-8")
            self.assertEqual(run_hook(repo, HOOK).returncode, 0)
            self.assertEqual(run(["--apply"], fake, board)[0], 0)
            git(repo, "add", "--", "board/007-cli-build-command.md")
            # When the hook runs on the generated blob
            accepted = run_hook(repo, HOOK)
            accepted_alias = run_hook(repo, HOOK_ALIAS)
            card = board / "007-cli-build-command.md"
            original = card.read_bytes()
            card.write_bytes(original.replace(b"Body.", b"Body. EDIT"))
            # And when the working tree changes but the index does not
            dirty = run_hook(repo, HOOK)
            git(repo, "add", "--", "board/007-cli-build-command.md")
            rejected = run_hook(repo, HOOK)
            card.write_bytes(original)
            git(repo, "add", "--", "board/007-cli-build-command.md")
            (board / "004-bare.md").write_bytes(b"# Bare\n\nno header\n")
            git(repo, "add", "--", "board/004-bare.md")
            bare = run_hook(repo, HOOK)
        # Then a generated card is accepted, a staged hand edit is rejected, and a missing header is rejected
        self.assertEqual(accepted.returncode, 0, accepted.stderr)
        self.assertEqual(accepted_alias.returncode, 0, accepted_alias.stderr)
        self.assertEqual(dirty.returncode, 0, dirty.stderr)
        self.assertEqual(rejected.returncode, 1)
        self.assertIn(message, rejected.stderr)
        self.assertEqual(bare.returncode, 1)
        self.assertIn(missing, bare.stderr)

    def test_before_the_cutover_marker_the_hook_lets_hand_edited_cards_through(self):
        # Given a repo that has NOT cut over (no board/CUTOVER) and a hand-written staged card
        with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
            repo = Path(tmp)
            (repo / "board").mkdir()
            init_repo(repo)
            (repo / "board" / "007-cli-build-command.md").write_bytes(b"# Hand\n\nno header\n")
            git(repo, "add", "--", "board/007-cli-build-command.md")
            # When the hook runs
            result = run_hook(repo, HOOK)
        # Then it accepts: the files are still the source until the cutover
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_after_the_cutover_marker_a_hand_written_card_is_rejected(self):
        with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
            repo = Path(tmp)
            (repo / "board").mkdir()
            init_repo(repo)
            (repo / "board" / "CUTOVER").write_text("cut over\n", encoding="utf-8")
            (repo / "board" / "007-cli-build-command.md").write_bytes(b"# Hand\n\nno header\n")
            git(repo, "add", "--", "board/007-cli-build-command.md")
            result = run_hook(repo, HOOK)
        self.assertEqual(result.returncode, 1)
        self.assertIn("generated archive", result.stderr)

    def test_hook_checks_only_the_rows_inside_the_board_table_markers(self):
        # Given a generated milestone staged on its own
        fake = FakeGH(issues=[], items=[item(1, 7, "CLI build command", "Ready", 1, "none", 15)])
        with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
            repo = Path(tmp)
            board = repo / "board"
            board.mkdir()
            (board / "MILESTONE-usable-v1.md").write_bytes(b"Intro stays.\n\nTail stays.\n")
            (board / "CUTOVER").write_text("cut over\n", encoding="utf-8")
            init_repo(repo)
            self.assertEqual(run(["--apply"], fake, board)[0], 0)
            git(repo, "add", "--", "board/MILESTONE-usable-v1.md")
            accepted = run_hook(repo, HOOK)
            milestone = board / "MILESTONE-usable-v1.md"
            text = milestone.read_bytes()
            milestone.write_bytes(text.replace(b"Intro stays.", b"Intro edited."))
            git(repo, "add", "--", "board/MILESTONE-usable-v1.md")
            prose = run_hook(repo, HOOK)
            milestone.write_bytes(milestone.read_bytes().replace(b"| Ready |", b"| Hand |"))
            git(repo, "add", "--", "board/MILESTONE-usable-v1.md")
            row = run_hook(repo, HOOK)
        # Then prose outside the markers is allowed and a row that breaks the hash is not
        self.assertEqual(accepted.returncode, 0, accepted.stderr)
        self.assertEqual(prose.returncode, 0, prose.stderr)
        self.assertEqual(row.returncode, 1)
        self.assertIn("board/MILESTONE-usable-v1.md is a generated archive", row.stderr)


class CutoverTests(unittest.TestCase):
    def test_cutover_refuses_apply_and_still_allows_dry_runs(self):
        # Given a temp board that contains the cutover marker
        with tempfile.TemporaryDirectory() as tmp:
            board = Path(tmp)
            (board / "001-one.md").write_bytes(b"# One\n\n- **Status:** Ready\n- **Type:** feature\n")
            (board / "CUTOVER").write_bytes(b"2026-10-26 the GitHub project is canonical\n")
            migrate_fake = ListGH()
            # When migrate --apply runs, and when a dry run runs
            apply_code, apply_out = run_migrate(["--apply"], migrate_fake, board)
            dry_fake = ListGH()
            dry_code, dry_out = run_migrate([], dry_fake, board)
            explicit_fake = ListGH()
            explicit_code, explicit_out = run_migrate(["--dry-run"], explicit_fake, board)
        # Then apply is refused and both dry runs still list the card
        self.assertEqual(apply_code, 1)
        self.assertIn("files-to-board direction is retired", apply_out)
        self.assertIn("The GitHub project is canonical", apply_out)
        self.assertEqual(migrate_fake.calls, [])
        self.assertEqual(dry_code, 0)
        self.assertIn("create (001) One", dry_out)
        self.assertNotIn("retired", dry_out)
        self.assertTrue(all(call[:2] == ["issue", "list"] for call in dry_fake.calls))
        self.assertEqual(explicit_code, 0)
        self.assertIn("create (001) One", explicit_out)
        self.assertNotIn("retired", explicit_out)

    def test_cutover_refuses_set_fields_apply_and_allows_a_dry_run(self):
        # Given the field fixture plus the cutover marker and one marked issue per card
        with tempfile.TemporaryDirectory() as tmp:
            board = fixture_board(tmp)
            (board / "CUTOVER").write_bytes(b"2026-10-26 the GitHub project is canonical\n")
            apply_fake = FieldGH()
            for number in range(1, 5):
                apply_fake.add_issue(100 + number, f"{number:03d}")
            # When --apply runs
            apply_code, apply_out = run_fields(["--apply"], apply_fake, board)
            dry_fake = FieldGH()
            for number in range(1, 5):
                dry_fake.add_issue(100 + number, f"{number:03d}")
            dry_code, dry_out = run_fields(["--dry-run"], dry_fake, board)
        # Then apply writes nothing and the dry run still reads the project
        self.assertEqual(apply_code, 1)
        self.assertIn("files-to-board direction is retired", apply_out)
        self.assertEqual(apply_fake.calls, [])
        self.assertEqual(apply_fake.items, [])
        self.assertEqual(dry_code, 0)
        self.assertNotIn("retired", dry_out)

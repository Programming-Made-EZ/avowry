LINK = re.compile(r"\[[^\]\n]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
SCHEME = re.compile(r"^[A-Za-z][A-Za-z0-9+.-]*:")


def tracked_paths():
    return set(git("ls-files", "-z").decode("utf-8").split("\0")) - {""}


def relative_links(text):
    """Every markdown link target that is neither a URL nor an anchor-only link, fragment and query stripped."""
    targets = []
    for raw in LINK.findall(text):
        if SCHEME.match(raw) or raw.startswith("#") or raw.startswith("//"):
            continue
        target = urllib.parse.unquote(raw.split("#", 1)[0].split("?", 1)[0])
        if target:
            targets.append(target)
    return targets


def resolves(source, target, tracked):
    """True when the link target, relative to the file that holds it, is a tracked file or a directory (exact case)."""
    base = posixpath.dirname(source)
    joined = target.lstrip("/") if target.startswith("/") else posixpath.join(base, target)
    path = posixpath.normpath(joined)
    if path == "." or path == "":
        return True
    if path == ".." or path.startswith("../"):
        return False
    return path in tracked or any(name.startswith(path.rstrip("/") + "/") for name in tracked)


def unresolved_links(files, tracked):
    """(source file, target) for every relative link in `files` ({path: text}) that does not resolve; plus the count."""
    bad = []
    count = 0
    for source, text in files.items():
        for target in relative_links(text):
            count += 1
            if not resolves(source, target, tracked):
                bad.append((source, target))
    return bad, count


class ScopedLinks(unittest.TestCase):
    def test_relative_links_in_scoped_files_resolve(self):
        # Given the nine scoped files and the set of tracked paths
        tracked = tracked_paths()
        files = {path: (REPO / path).read_text(encoding="utf-8") for path in SCOPED}

        # When every relative markdown link is resolved against the folder of the file that holds it (URLs, anchors
        # and fragments tolerated, directories allowed, exact case)
        bad, count = unresolved_links(files, tracked)

        # Then the scan is not vacuous and every link points at a tracked file or directory
        self.assertGreaterEqual(count, 15, "fewer than 15 relative links found: the scan is vacuous")
        self.assertEqual([], bad, f"unresolved links ({len(bad)} of {count}): {bad}")


